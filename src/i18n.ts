/** pt-* → Brazilian Portuguese, es-* → Spanish, anything else → English */
export function strings(lang?: string): Strings {
  const l = lang?.toLowerCase() ?? '';
  if (l.startsWith('pt')) return pt;
  if (l.startsWith('es')) return es;
  return en;
}

/** idioma do usuário no HA (perfil), senão o do navegador */
export function langOf(hass?: { language?: string; locale?: { language?: string } }) {
  return hass?.locale?.language ?? hass?.language ?? (typeof navigator !== 'undefined' ? navigator.language : undefined);
}
